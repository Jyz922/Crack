"""Length-based calibration of raw sound similarity.

Raw ``sim`` is compressed: random same-length CMUdict word pairs already score
about 0.72-0.74, and one voicing change scores 0.994. ``calibrate`` rescales
against the random-pair mean μ_L for the segment length L of the longer word:

    sim_cal = (sim − μ_L) / (1 − μ_L)

so a random pair scores about 0 and identical pronunciations score 1. Values
below 0 (less alike than an average random pair) are kept, not clipped.
μ_L comes from data/phonetic_calibration.json, regenerated by
scripts/fit_phonetic_calibration.py with a fixed seed. Lengths outside the
table use the nearest stored length.
"""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

CALIBRATION_PATH = Path(__file__).resolve().parents[3] / "data" / "phonetic_calibration.json"


@lru_cache(maxsize=1)
def calibration_table() -> dict:
    if not CALIBRATION_PATH.exists():
        raise FileNotFoundError(
            f"{CALIBRATION_PATH} is missing; run scripts/fit_phonetic_calibration.py"
        )
    return json.loads(CALIBRATION_PATH.read_text(encoding="utf-8"))


def stored_lengths() -> list[int]:
    return sorted(int(length) for length in calibration_table()["lengths"])


def baseline_mean(length: int) -> float:
    lengths = stored_lengths()
    nearest = min(lengths, key=lambda stored: (abs(stored - length), stored))
    return calibration_table()["lengths"][str(nearest)]["mean"]


def calibrate(sim: float, length: int) -> float:
    mu = baseline_mean(length)
    return (sim - mu) / (1 - mu)
